"""
User database model.
Represents platform users with authentication and role-based access control.
"""

from sqlalchemy import Boolean, Column, DateTime, Enum as SqlEnum, Integer, String
from sqlalchemy.orm import relationship
from datetime import datetime, timezone
from app.db.session import Base
from app.models.enums import UserRole


class User(Base):
    """
    User model for authentication and authorization.

    Attributes:
        id (int): Primary key.
        email (str): User email address (unique).
        hashed_password (str): Bcrypt hashed password.
        full_name (str): User's full name.
        role (str): User role - 'admin' or 'analyst'.
        is_active (bool): Whether user account is active.
        created_at (datetime): Account creation timestamp.
        reports (relationship): Reports generated by this user (via Report.author).
    """

    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    email = Column(String(255), unique=True, index=True, nullable=False)
    hashed_password = Column(String(255), nullable=False)
    full_name = Column(String(255), nullable=False)
    role = Column(
        SqlEnum(UserRole, values_callable=lambda roles: [role.value for role in roles],
                native_enum=False, create_constraint=True),
        default=UserRole.TOPIC_MONITOR.value,
        nullable=False,
    )
    is_active = Column(Boolean, default=True, nullable=False)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    # Relationship to reports created by this user
    # back_populates must match the relationship attribute name in Report model
    reports = relationship("Report", back_populates="author", cascade="all, delete-orphan")
    created_topics = relationship("Topic", back_populates="created_by")
    user_topics = relationship("UserTopic", back_populates="user", cascade="all, delete-orphan")

    @property
    def topic_ids(self) -> list[int]:
        return [assignment.topic_id for assignment in self.user_topics]

    def __repr__(self) -> str:
        return f"<User(id={self.id}, email='{self.email}', role='{self.role}')>"

    def __str__(self) -> str:
        return f"{self.full_name} ({self.email}) - {self.role}"
